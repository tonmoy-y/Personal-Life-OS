import "server-only";

/**
 * Best-effort in-memory sliding-window limiter. State is per server instance (serverless instances
 * do not share it), so it only blunts bursts from a single instance — Supabase Auth's own rate limits
 * are the authoritative control. Documented in README.
 */
const buckets = new Map<string, number[]>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const hits = (buckets.get(key) ?? []).filter((t) => now - t < windowMs);
  if (hits.length >= limit) {
    buckets.set(key, hits);
    return false;
  }
  hits.push(now);
  buckets.set(key, hits);
  if (buckets.size > 5000) for (const [k, v] of buckets) if (!v.some((t) => now - t < windowMs)) buckets.delete(k);
  return true;
}
